def check_residual_block(block_cls):
    """Exercise 3a -- the identity test is what proves the skip is wired up."""
    try:
        block = block_cls(16)
    except NotImplementedError:
        raise CheckFailed("ResidualBlock is not implemented yet.")
    check(isinstance(block, nn.Module), "ResidualBlock should subclass nn.Module.")
    check(
        n_conv(block) == 2,
        f"the block holds {n_conv(block)} Conv2d layers, expected 2.",
    )
    z = torch.rand(4, 16, 14, 14)  # non-negative, so a trailing ReLU is the identity
    with torch.no_grad():
        out = block(z)
    check(
        out.shape == z.shape,
        f"the block changed the shape from {tuple(z.shape)} to {tuple(out.shape)}; a residual "
        "block must preserve it, or the addition cannot happen.",
    )
    # zero the second convolution: the block must now be the identity
    convs = [m for m in block.modules() if isinstance(m, nn.Conv2d)]
    with torch.no_grad():
        nn.init.zeros_(convs[-1].weight)
        if convs[-1].bias is not None:
            nn.init.zeros_(convs[-1].bias)
        out = block(z)
    check(
        torch.allclose(out, z, atol=1e-6),
        f"with the second convolution zeroed the block should return its input unchanged, "
        f"but the largest difference is {(out - z).abs().max():.4g}. That means the skip "
        "connection is missing -- the block must compute z + f(z), not just f(z).",
    )
    print("[ok] 3a: the block preserves shape, and reduces to the identity when f is zeroed.")


