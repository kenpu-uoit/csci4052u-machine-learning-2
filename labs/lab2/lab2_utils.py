class MNISTDataModule(L.LightningDataModule):
    """A fixed stratified subsample of MNIST, small enough for four CPU runs.

    The subsample indices are drawn with a fixed generator, so every student
    trains on exactly the same images as the marker.
    """

    def __init__(self, n_train=N_TRAIN, n_test=N_TEST, batch_size=BATCH):
        super().__init__()
        self.save_hyperparameters()
        self.tf = transforms.Compose(
            [transforms.ToTensor(), transforms.Normalize((MEAN,), (STD,))]
        )

    def prepare_data(self):
        torchvision.datasets.MNIST(DATA_DIR, train=True, download=True)
        torchvision.datasets.MNIST(DATA_DIR, train=False, download=True)

    def setup(self, stage=None):
        full_train = torchvision.datasets.MNIST(
            DATA_DIR, train=True, download=False, transform=self.tf
        )
        full_test = torchvision.datasets.MNIST(
            DATA_DIR, train=False, download=False, transform=self.tf
        )
        g = torch.Generator().manual_seed(0)
        idx = torch.randperm(len(full_train), generator=g)[: self.hparams.n_train]
        self.train_set = Subset(full_train, idx.tolist())
        g = torch.Generator().manual_seed(1)
        idx = torch.randperm(len(full_test), generator=g)[: self.hparams.n_test]
        self.test_set = Subset(full_test, idx.tolist())

    def train_dataloader(self):
        return DataLoader(
            self.train_set, batch_size=self.hparams.batch_size, shuffle=True
        )

    def val_dataloader(self):
        return DataLoader(self.train_set, batch_size=512)

    def test_dataloader(self):
        return DataLoader(self.test_set, batch_size=512)


