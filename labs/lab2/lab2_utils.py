def show_digits(dm, n=8):
    dm.setup()
    x, y = next(iter(DataLoader(dm.train_set, batch_size=n, shuffle=False)))
    fig, axes = plt.subplots(1, n, figsize=(1.3 * n, 1.8))
    for ax, img, label in zip(axes, x, y):
        ax.imshow(img.squeeze() * STD + MEAN, cmap="gray")
        ax.set_title(int(label), fontsize=10)
        ax.axis("off")
    fig.suptitle(f"MNIST subsample: {len(dm.train_set)} train, {len(dm.test_set)} test")
    plt.tight_layout()
    plt.show()


def plot_curves(histories, title="training loss", chance=True):
    """histories: dict of name -> History (or list of losses)."""
    fig, ax = plt.subplots(figsize=(6, 3.6))
    for name, h in histories.items():
        losses = h.losses if hasattr(h, "losses") else h
        ax.plot(range(1, len(losses) + 1), losses, marker="o", label=name)
    if chance:
        ax.axhline(
            CHANCE_LOSS, ls="--", color="0.5",
            label=f"chance, ln 10 = {CHANCE_LOSS:.3f}",
        )
    ax.set_xlabel("epoch")
    ax.set_ylabel("training loss")
    ax.set_title(title)
    ax.legend(fontsize=8)
    plt.tight_layout()
    plt.show()


