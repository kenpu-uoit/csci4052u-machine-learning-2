def reference_conv_block(c_in, c_out):
    """Exercise 1a's answer, used only to check the student's version."""
    return nn.Sequential(
        nn.Conv2d(c_in, c_out, kernel_size=3, padding=1),
        nn.ReLU(),
        nn.MaxPool2d(2),
    )


STAGES = [(1, 16), (16, 32), (32, 64)]  # every network uses these widths
HEAD_IN = 64 * 3 * 3                    # 28 -> 14 -> 7 -> 3


def n_conv(model):
    """Number of Conv2d modules anywhere in the model."""
    return sum(1 for m in model.modules() if isinstance(m, nn.Conv2d))


def n_params(model):
    return sum(p.numel() for p in model.parameters())


