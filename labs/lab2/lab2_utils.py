class LitClassifier(L.LightningModule):
    """Wraps any backbone into a Lightning module.

    Exercise 1c asks only for ``training_step``; everything else is provided,
    and the same subclass is then reused for all four networks.
    """

    def __init__(self, net, lr=LR):
        super().__init__()
        self.net = net
        self.lr = lr
        self.train_acc = MulticlassAccuracy(num_classes=10)
        self.test_acc = MulticlassAccuracy(num_classes=10)

    def forward(self, x):
        return self.net(x)

    def training_step(self, batch, batch_idx):
        raise NotImplementedError("Exercise 1c: implement training_step")

    # -- provided --
    def configure_optimizers(self):
        return torch.optim.SGD(self.parameters(), lr=self.lr, momentum=0.9)

    def validation_step(self, batch, batch_idx):
        x, y = batch
        logits = self(x)
        self.log("train_loss", F.cross_entropy(logits, y), on_epoch=True)
        self.log("train_acc", self.train_acc(logits, y), on_epoch=True, prog_bar=True)

    def test_step(self, batch, batch_idx):
        x, y = batch
        logits = self(x)
        self.log("test_acc", self.test_acc(logits, y), prog_bar=True)


def make_trainer(max_epochs=EPOCHS, quiet=True, callbacks=None):
    """A CPU trainer that keeps every student's numbers identical to the marker's."""
    return L.Trainer(
        max_epochs=max_epochs,
        callbacks=callbacks or [],
        accelerator="cpu",
        logger=False,
        enable_checkpointing=False,
        enable_model_summary=False,
        enable_progress_bar=not quiet,
        log_every_n_steps=10,
        num_sanity_val_steps=0,
    )


class History(L.Callback):
    """Collects the per-epoch training loss and accuracy so they can be plotted."""

    def __init__(self):
        self.losses, self.accs = [], []

    def on_validation_epoch_end(self, trainer, pl_module):
        m = trainer.callback_metrics
        loss = m.get("train_loss_epoch", m.get("train_loss"))
        acc = m.get("train_acc_epoch", m.get("train_acc"))
        if loss is not None:
            self.losses.append(float(loss))
        if acc is not None:
            self.accs.append(float(acc))


def fit(model, dm, max_epochs=EPOCHS, seed=0):
    """Train a LitClassifier and return (history, test_accuracy).

    Re-seeds first, so every run starts from the same initialisation.
    """
    L.seed_everything(seed, workers=True)
    hist = History()
    trainer = make_trainer(max_epochs, callbacks=[hist])
    trainer.fit(model, datamodule=dm)
    test_acc = float(trainer.test(model, datamodule=dm, verbose=False)[0]["test_acc"])
    return hist, test_acc


def first_conv_grad_norm(net, batch):
    """Gradient norm at the first convolution after one backward pass.

    Provided so Exercise 3c measures gradient flow without boilerplate.
    """
    net.zero_grad()
    x, y = batch
    F.cross_entropy(net(x), y).backward()
    first = next(m for m in net.modules() if isinstance(m, nn.Conv2d))
    return float(first.weight.grad.norm())


