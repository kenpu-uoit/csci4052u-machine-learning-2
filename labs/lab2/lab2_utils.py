class CheckFailed(AssertionError):
    pass


def check(condition, message):
    if not condition:
        raise CheckFailed(message)


def check_conv_block(fn):
    """Exercise 1a."""
    try:
        got = fn(1, 16)
    except NotImplementedError:
        raise CheckFailed("conv_block is not implemented yet.")
    x = torch.randn(8, 1, 28, 28)
    with torch.no_grad():
        out = got(x)
    check(
        out.shape == (8, 16, 14, 14),
        f"conv_block(1, 16) on a (8,1,28,28) input gave {tuple(out.shape)}, "
        "expected (8, 16, 14, 14) -- is the MaxPool2d(2) there, and padding=1 on the conv?",
    )
    for c_in, c_out in [(1, 16), (16, 32), (32, 64)]:
        want = 9 * c_in * c_out + c_out
        have = n_params(fn(c_in, c_out))
        check(
            have == want,
            f"conv_block({c_in}, {c_out}) has {have} parameters, expected {want} "
            f"= 9*{c_in}*{c_out} + {c_out} -- a 3x3 kernel per input/output channel pair, "
            "plus one bias per output channel.",
        )
    check(
        n_conv(fn(1, 16)) == 1,
        f"conv_block should hold exactly one Conv2d, found {n_conv(fn(1, 16))}.",
    )
    print("[ok] 1a: conv_block halves the resolution and has 9*c_in*c_out + c_out parameters.")


