def check_gaussian_nll(fn):
    """Exercise 2a."""
    g = torch.Generator().manual_seed(1)
    pred = torch.randn(25, 1, generator=g)
    y = pred + 0.3 * torch.randn(25, 1, generator=g)
    for sigma in (0.5, 1.0, 2.0):
        try:
            got = float(fn(pred, y, sigma))
        except NotImplementedError:
            raise CheckFailed("gaussian_nll is not implemented yet.")
        sse = float(((y - pred) ** 2).sum())
        want = 0.5 * sse / sigma**2 + len(y) * math.log(math.sqrt(2 * math.pi) * sigma)
        check(
            abs(got - want) < 1e-4,
            f"at sigma={sigma} you returned {got:.4f}, expected {want:.4f}. "
            "The NLL is 0.5 * SSE / sigma^2 + I * log(sqrt(2 pi) sigma).",
        )
    # the two criteria must rank parameter sets identically
    good, bad = pred, pred + 2.0
    check(
        (fn(good, y, 1.0) < fn(bad, y, 1.0))
        == (((y - good) ** 2).sum() < ((y - bad) ** 2).sum()),
        "your NLL ranks a good and a bad fit differently from least squares; "
        "they must agree, because least squares IS the Gaussian NLL up to a constant.",
    )
    print("[ok] 2a: your NLL equals 0.5*SSE/sigma^2 + const, and ranks fits like least squares.")


