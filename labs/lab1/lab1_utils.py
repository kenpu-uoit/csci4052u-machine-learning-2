class LitClassifier(L.LightningModule):
    """A two-hidden-layer classifier for MNIST-1D.

    Exercise 2c asks only for ``training_step``; everything else is provided.
    """

    def __init__(self, width=100, lr=0.1, n_inputs=40, n_classes=10):
        super().__init__()
        self.save_hyperparameters()
        self.net = nn.Sequential(
            nn.Linear(n_inputs, width),
            nn.ReLU(),
            nn.Linear(width, width),
            nn.ReLU(),
            nn.Linear(width, n_classes),
        )
        self.train_acc = MulticlassAccuracy(num_classes=n_classes)
        self.test_acc = MulticlassAccuracy(num_classes=n_classes)

    def forward(self, x):
        return self.net(x)

    def training_step(self, batch, batch_idx):
        raise NotImplementedError("Exercise 2c: implement training_step")

    # -- provided --
    def configure_optimizers(self):
        return torch.optim.SGD(self.parameters(), lr=self.hparams.lr, momentum=0.9)

    def validation_step(self, batch, batch_idx):
        x, y = batch
        logits = self(x)
        self.log("train_loss", F.cross_entropy(logits, y))
        self.log("train_acc", self.train_acc(logits, y), prog_bar=True)

    def test_step(self, batch, batch_idx):
        x, y = batch
        logits = self(x)
        self.log("test_loss", F.cross_entropy(logits, y))
        self.log("test_acc", self.test_acc(logits, y), prog_bar=True)


