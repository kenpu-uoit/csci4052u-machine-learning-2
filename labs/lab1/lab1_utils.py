class CheckFailed(AssertionError):
    pass


def check(condition, message):
    if not condition:
        raise CheckFailed(message)


def check_shallow_forward(fn):
    """Exercise 1a."""
    x = torch.linspace(0, 2, 1000)
    try:
        got = fn(x, EXAMPLE_THETA, EXAMPLE_PHI)
    except NotImplementedError:
        raise CheckFailed("shallow_forward is not implemented yet.")
    check(isinstance(got, torch.Tensor), f"expected a tensor, got {type(got).__name__}.")
    check(
        got.shape == x.shape,
        f"your output has shape {tuple(got.shape)}, expected {tuple(x.shape)} -- "
        "did you forget to sum over the hidden units?",
    )
    with torch.no_grad():
        want = reference_shallow_net(EXAMPLE_THETA, EXAMPLE_PHI)(x.unsqueeze(1)).squeeze(1)
    check(
        torch.allclose(got, want, atol=1e-6),
        f"largest disagreement with the reference network is {(got - want).abs().max():.4g}; "
        "check the ReLU and the output offset phi[0].",
    )
    print("[ok] 1a: shallow_forward matches the reference network to 1e-6.")


