def plot_datasets(sine, mnist1d):
    fig, ax = plt.subplots(1, 2, figsize=(10, 3.2))
    ax[0].scatter(sine.x_train, sine.y_train, s=18, label="train")
    ax[0].scatter(sine.x_test, sine.y_test, s=6, alpha=0.35, label="test")
    ax[0].set(xlabel="$x$", ylabel="$y$", title="1D sine regression")
    ax[0].legend(fontsize=8)
    for k in range(3):
        idx = (mnist1d.y_train == k).nonzero()[0].item()
        ax[1].plot(mnist1d.x_train[idx], label=f"digit {k}")
    ax[1].set(xlabel="position", ylabel="value", title="MNIST-1D (3 examples)")
    ax[1].legend(fontsize=8)
    fig.tight_layout()
    plt.show()


def plot_fit(model, dm, title="fitted function"):
    grid = torch.linspace(0, 1, 400).unsqueeze(1)
    with torch.no_grad():
        pred = model(grid)
    fig, ax = plt.subplots(figsize=(5, 3.2))
    ax.scatter(dm.x_train, dm.y_train, s=18, color="0.4", label="train data")
    ax.plot(grid, pred, color="#2c5f70", lw=2, label="model")
    ax.set(xlabel="$x$", ylabel="$y$", title=title)
    ax.legend(fontsize=8)
    fig.tight_layout()
    plt.show()


def plot_capacity_sweep(widths, train_errors, test_errors, noise_floor=None):
    fig, ax = plt.subplots(figsize=(5.2, 3.4))
    ax.plot(widths, train_errors, "o-", label="train MSE")
    ax.plot(widths, test_errors, "s-", label="test MSE")
    if noise_floor is not None:
        ax.axhline(noise_floor, color="0.5", ls=":",
                   label=f"noise floor $\\sigma^2$ = {noise_floor:.3f}")
    ax.set_xscale("log", base=2)
    ax.set(xlabel="hidden width (capacity)", ylabel="mean squared error",
           title="capacity against error")
    ax.legend(fontsize=8)
    fig.tight_layout()
    plt.show()


