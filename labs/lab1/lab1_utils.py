def reference_shallow_net(theta, phi):
    """The same shallow network as Exercise 1, built as an ``nn.Sequential``.

    ``theta`` is (D, 2) holding the intercept and slope of each hidden unit;
    ``phi`` is (D + 1,) holding the output offset followed by the output weights.
    """
    d = theta.shape[0]
    net = nn.Sequential(nn.Linear(1, d), nn.ReLU(), nn.Linear(d, 1))
    with torch.no_grad():
        net[0].bias.copy_(theta[:, 0])
        net[0].weight.copy_(theta[:, 1].unsqueeze(1))
        net[2].bias.copy_(phi[:1])
        net[2].weight.copy_(phi[1:].unsqueeze(0))
    return net


