def make_sine_data(n, noise=0.1, seed=0):
    """``n`` points of y = sin(2 pi x) + noise, with x drawn uniformly on [0, 1]."""
    g = torch.Generator().manual_seed(seed)
    x = torch.rand(n, generator=g)
    y = torch.sin(2 * math.pi * x) + noise * torch.randn(n, generator=g)
    return x.unsqueeze(1), y.unsqueeze(1)


class SineDataModule(L.LightningDataModule):
    """The 1D regression set.  ``n_train`` points to fit, ``n_test`` held out."""

    def __init__(self, n_train=60, n_test=200, batch_size=16, noise=0.1):
        super().__init__()
        self.save_hyperparameters()
        self.noise = noise
        x, y = make_sine_data(n_train + n_test, noise=noise, seed=0)
        self.x_train, self.y_train = x[:n_train], y[:n_train]
        self.x_test, self.y_test = x[n_train:], y[n_train:]

    def train_dataloader(self):
        ds = TensorDataset(self.x_train, self.y_train)
        return DataLoader(ds, batch_size=self.hparams.batch_size, shuffle=True)

    def val_dataloader(self):
        # the training points again, scored in one batch -- this is the train error
        ds = TensorDataset(self.x_train, self.y_train)
        return DataLoader(ds, batch_size=len(ds))

    def test_dataloader(self):
        ds = TensorDataset(self.x_test, self.y_test)
        return DataLoader(ds, batch_size=len(ds))


def download_mnist1d(data_dir=DATA_DIR):
    """Fetch the MNIST-1D pickle once and cache it, so re-runs work offline."""
    data_dir = Path(data_dir)
    data_dir.mkdir(exist_ok=True)
    path = data_dir / "mnist1d_data.pkl"
    if not path.exists():
        print(f"downloading MNIST-1D to {path} ...")
        urllib.request.urlretrieve(MNIST1D_URL, path)
    with open(path, "rb") as fh:
        return pickle.load(fh)


class MNIST1DDataModule(L.LightningDataModule):
    """MNIST-1D: 4000 training and 1000 test examples, 40 inputs, 10 classes."""

    def __init__(self, batch_size=100, label_noise=0.0):
        super().__init__()
        self.save_hyperparameters()
        d = download_mnist1d()
        self.x_train = torch.tensor(d["x"], dtype=torch.float32)
        self.y_train = torch.tensor(d["y"], dtype=torch.long)
        self.x_test = torch.tensor(d["x_test"], dtype=torch.float32)
        self.y_test = torch.tensor(d["y_test"], dtype=torch.long)
        if label_noise > 0:  # used only by the optional double-descent experiment
            g = torch.Generator().manual_seed(0)
            n = int(label_noise * len(self.y_train))
            idx = torch.randperm(len(self.y_train), generator=g)[:n]
            self.y_train[idx] = torch.randint(0, 10, (n,), generator=g)

    def train_dataloader(self):
        ds = TensorDataset(self.x_train, self.y_train)
        return DataLoader(ds, batch_size=self.hparams.batch_size, shuffle=True)

    def val_dataloader(self):
        ds = TensorDataset(self.x_train, self.y_train)
        return DataLoader(ds, batch_size=1000)

    def test_dataloader(self):
        ds = TensorDataset(self.x_test, self.y_test)
        return DataLoader(ds, batch_size=1000)


